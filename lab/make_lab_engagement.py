"""RC-28: RC-20 follow-up: make the lab harness teardown idempotent (down-before-up)

Writes a run-specific copy of the lab engagement template
(``lab/engagement.yaml``) whose ``authorization.window`` is
``[now - 5 min, now + N h]`` in UTC. Every other field is copied unchanged,
and that is checked before writing. The written file is then loaded through
``op06d.engagement.load_engagement``; if it does not load, it is deleted and
the script exits non-zero.

Runs inside the scanner (PyYAML and op06d are installed there):

    python3 /lab/make_lab_engagement.py <out.yaml> [--hours N] [--template /lab/engagement.yaml]

The template is only read, never written. ``<out.yaml>`` goes under the
writable ``/captures`` mount.
"""

from __future__ import annotations

import argparse
import copy
import datetime as dt
import pathlib
import sys
from typing import Any

import yaml

DEFAULT_HOURS = 4.0
LEAD = dt.timedelta(minutes=5)
TIME_FORMAT = "%Y-%m-%dT%H:%M:%SZ"


class TemplateError(ValueError):
    """The template cannot be turned into a run-specific engagement."""


def window_for(now: dt.datetime, hours: float) -> tuple[dt.datetime, dt.datetime]:
    """``[now - 5 min, now + hours]``, UTC, whole seconds."""
    if now.tzinfo is None:
        raise ValueError("now must be timezone-aware")
    if not hours > 0:
        raise ValueError(f"hours must be positive, got {hours!r}")
    now = now.astimezone(dt.timezone.utc).replace(microsecond=0)
    return now - LEAD, now + dt.timedelta(hours=hours)


def make_engagement(template: Any, now: dt.datetime, hours: float = DEFAULT_HOURS) -> dict:
    """A deep copy of ``template`` with only ``authorization.window`` replaced.
    A template without an ``authorization`` mapping that already has a
    ``window`` is refused, not patched."""
    if not isinstance(template, dict):
        raise TemplateError("template is not a YAML mapping")
    auth = template.get("authorization")
    if not isinstance(auth, dict):
        raise TemplateError("template has no 'authorization' mapping")
    if "window" not in auth:
        raise TemplateError("template has no 'authorization.window' to replace")
    start, end = window_for(now, hours)
    out = copy.deepcopy(template)
    out["authorization"]["window"] = [start.strftime(TIME_FORMAT), end.strftime(TIME_FORMAT)]
    assert_only_window_differs(template, out)
    return out


def assert_only_window_differs(template: dict, generated: dict) -> None:
    """Raise unless ``generated`` equals ``template`` apart from
    ``authorization.window``."""
    a, b = copy.deepcopy(template), copy.deepcopy(generated)
    for d in (a, b):
        if isinstance(d.get("authorization"), dict):
            d["authorization"].pop("window", None)
    if a != b:
        raise TemplateError("generated engagement differs from the template outside authorization.window")


def write_engagement(template_path: pathlib.Path, out_path: pathlib.Path, *,
                     now: dt.datetime | None = None, hours: float = DEFAULT_HOURS) -> dict:
    """Generate, write and validate. Returns the generated mapping."""
    from op06d.engagement import load_engagement

    if out_path.resolve() == template_path.resolve():
        raise TemplateError("refusing to overwrite the template")
    template = yaml.safe_load(template_path.read_text(encoding="utf-8"))
    generated = make_engagement(template, now or dt.datetime.now(dt.timezone.utc), hours)
    header = (f"# Generated by lab/make_lab_engagement.py from {template_path} - do not edit.\n"
              f"# Only authorization.window differs from the template.\n")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(header + yaml.safe_dump(generated, sort_keys=False), encoding="utf-8")
    try:
        load_engagement(out_path)
    except Exception:
        out_path.unlink(missing_ok=True)
        raise
    return generated


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write a run-specific lab engagement with a window around now.")
    parser.add_argument("out", type=pathlib.Path)
    parser.add_argument("--template", type=pathlib.Path, default=pathlib.Path("/lab/engagement.yaml"))
    parser.add_argument("--hours", type=float, default=DEFAULT_HOURS)
    args = parser.parse_args(argv)
    try:
        generated = write_engagement(args.template, args.out, hours=args.hours)
    except Exception as exc:
        print(f"ERROR: could not generate {args.out}: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    start, end = generated["authorization"]["window"]
    print(f"wrote {args.out} (window {start} .. {end}; validated)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
